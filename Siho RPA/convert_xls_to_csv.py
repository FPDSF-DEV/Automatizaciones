import argparse
import sys
import unicodedata
from pathlib import Path

import pandas as pd

# Columnas de metadatos que NO deben quedar en la informacion organizada:
# se eliminan tanto de los CSV como de los consolidados .xlsx.
DROP_COLUMNS = {
    "ano", "mes", "depa_codigo", "departamento", "muni_codigo", "municipio",
    "codigo_habilitacion", "nivel", "convenio_reestructuracion", "caracter",
    "ese", "habilitado", "conc_codigo", "fecha_creacion", "fecha_modificacion",
    "usu_id_usuario", "ip", "captura",
}


# Encabezados tipicos del SIHO (ademas de DROP_COLUMNS) usados solo para
# RECONOCER que la primera fila de una tabla es el encabezado real.
HEADER_TOKENS = DROP_COLUMNS | {
    "nombre", "concepto", "secuencia", "vigencia_actual",
    "codigo_sede", "nombre_sede", "latitud", "longitud",
    "tipo_institucion", "ubicacion", "area_lote", "area_construida",
}


def _normalize_column(name) -> str:
    """Normaliza un encabezado para compararlo: sin tildes, minusculas,
    espacios como guion bajo (asi 'Año' y 'ano' coinciden)."""
    text = unicodedata.normalize("NFKD", str(name)).encode("ascii", "ignore").decode("ascii")
    return text.strip().lower().replace(" ", "_")


def drop_metadata_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Elimina las columnas de DROP_COLUMNS (si existen) del DataFrame."""
    if isinstance(df.columns, pd.MultiIndex):
        return df
    to_drop = [c for c in df.columns if _normalize_column(c) in DROP_COLUMNS]
    return df.drop(columns=to_drop) if to_drop else df


def make_safe_sheet_name(sheet_name: str) -> str:
    """Normalize sheet names for safe file names."""
    invalid = '<>:"/\\|?*'
    safe = ''.join('_' if c in invalid else c for c in str(sheet_name)).strip()
    return safe or 'hoja'


def has_autogenerated_numeric_columns(df: pd.DataFrame) -> bool:
    """Detect headers like 0,1,2,... produced automatically by pandas."""
    cols = list(df.columns)
    expected = list(range(len(cols)))

    normalized = []
    for col in cols:
        if isinstance(col, int):
            normalized.append(col)
            continue
        text = str(col).strip()
        if text.isdigit():
            normalized.append(int(text))
        else:
            return False

    return normalized == expected


def promote_header_row(df: pd.DataFrame) -> pd.DataFrame:
    """Cuando pandas no detecta encabezado (columnas 0,1,2,...) pero la
    primera fila ES el encabezado real (caso tablas HTML del SIHO), la
    promueve a nombres de columna. Se reconoce porque la fila contiene
    varios nombres conocidos de metadatos (ano, mes, depa_codigo, ...)."""
    if df.empty or not has_autogenerated_numeric_columns(df):
        return df
    first = df.iloc[0]
    matches = sum(1 for v in first if _normalize_column(v) in HEADER_TOKENS)
    if matches < 3:
        return df
    promoted = df.iloc[1:].reset_index(drop=True)
    promoted.columns = [str(v).strip() for v in first]
    return promoted


def export_df_to_csv(df: pd.DataFrame, output_file: Path) -> None:
    """Write CSV in UTF-8, dropping only synthetic numeric headers."""
    df = drop_metadata_columns(promote_header_row(df))
    write_header = not has_autogenerated_numeric_columns(df)
    df.to_csv(output_file, index=False, encoding="utf-8", header=write_header)


def normalize_sheet_name(name: str) -> str:
    """Create a valid Excel sheet name (max 31 chars, no invalid chars)."""
    invalid = '[]:*?/\\'
    cleaned = ''.join('_' if c in invalid else c for c in str(name)).strip().strip("'")
    cleaned = cleaned or "hoja"
    return cleaned[:31]


def build_unique_sheet_name(base_name: str, used_names: set[str]) -> str:
    """Ensure unique sheet names inside one workbook."""
    candidate = normalize_sheet_name(base_name)
    if candidate not in used_names:
        used_names.add(candidate)
        return candidate

    suffix = 1
    while True:
        suffix_text = f"_{suffix}"
        max_base = 31 - len(suffix_text)
        short_base = candidate[:max_base]
        attempt = f"{short_base}{suffix_text}"
        if attempt not in used_names:
            used_names.add(attempt)
            return attempt
        suffix += 1


def build_sheet_base_name(top_dir_name: str, top_dir: Path, csv_file: Path) -> str:
    """Build concise sheet names with year, and trimester when present."""
    relative_csv = csv_file.relative_to(top_dir).with_suffix("")
    parts = list(relative_csv.parts)
    file_stem = parts[-1] if parts else csv_file.stem

    year = ""
    for p in parts:
        if len(p) == 4 and p.isdigit():
            year = p
            break

    if not year:
        for token in file_stem.split("_"):
            if len(token) == 4 and token.isdigit():
                year = token
                break

    quarter_markers = ["enero-mar", "abril-jun", "julio-sep", "octubre-dic"]
    quarter = ""
    lower_stem = file_stem.lower()
    for marker in quarter_markers:
        if marker in lower_stem:
            quarter = marker
            break

    item_name = ""
    if len(parts) >= 2:
        item_name = parts[-2]
    elif parts:
        item_name = parts[-1]

    if top_dir_name.lower() in {"formularios_trimestrales", "consultas_detalladas"} and quarter:
        base = "_".join(filter(None, [year, quarter, item_name]))
    else:
        base = "_".join(filter(None, [year, item_name]))

    return base or "hoja"


def _consolidate_dir(source_dir: Path, workbook_path: Path, sheet_top_name: str) -> tuple[int, int]:
    """Create one Excel workbook with one sheet per CSV under source_dir."""
    csv_files = sorted(source_dir.rglob("*.csv"))
    if not csv_files:
        return 0, 0

    used_sheet_names: set[str] = set()
    failed = 0

    try:
        with pd.ExcelWriter(workbook_path, engine="openpyxl") as writer:
            for csv_file in csv_files:
                try:
                    df = drop_metadata_columns(pd.read_csv(csv_file, encoding="utf-8"))
                    sheet_base = build_sheet_base_name(sheet_top_name, source_dir, csv_file)
                    sheet_name = build_unique_sheet_name(sheet_base, used_sheet_names)
                    df.to_excel(writer, sheet_name=sheet_name, index=False)
                except Exception as exc:
                    print(f"[ERROR] Fallo al agregar CSV al Excel ({csv_file}): {exc}")
                    failed += 1

        print(f"[OK][XLSX] Consolidado creado: {workbook_path}")
        return 1, failed
    except Exception as exc:
        print(f"[ERROR] No se pudo crear Excel consolidado ({workbook_path}): {exc}")
        return 0, failed + 1


def build_workbooks_from_csv(output_root: Path) -> tuple[int, int]:
    """Consolida los CSV en libros de Excel.

    Con el layout por entidad (descargas_csv/<entidad>/<categoria>/...) crea
    un libro por categoria DENTRO de la carpeta de la entidad. Las carpetas
    planas con CSV sueltos (p.ej. salidas de otros scripts de analisis) se
    consolidan como antes: un libro por carpeta en la raiz."""
    created = 0
    failed = 0

    for top_dir in sorted(p for p in output_root.iterdir() if p.is_dir()):
        sub_dirs = sorted(d for d in top_dir.iterdir() if d.is_dir())
        loose_csvs = list(top_dir.glob("*.csv"))

        if sub_dirs and not loose_csvs:
            # Carpeta de entidad: un consolidado por categoria.
            for cat_dir in sub_dirs:
                c, f = _consolidate_dir(cat_dir, top_dir / f"{cat_dir.name}.xlsx", cat_dir.name)
                created += c
                failed += f
        else:
            c, f = _consolidate_dir(top_dir, output_root / f"{top_dir.name}.xlsx", top_dir.name)
            created += c
            failed += f

    if created == 0 and failed == 0:
        print(f"[WARN] Sin CSV para consolidar en: {output_root}")

    return created, failed


def try_read_excel(source_file: Path, sheet_name):
    """Try reading with explicit engines before falling back to HTML parsing."""
    suffix = source_file.suffix.lower()
    engine_candidates = []

    if suffix == ".xlsx":
        engine_candidates = ["openpyxl"]
    elif suffix == ".xls":
        engine_candidates = ["xlrd", "openpyxl"]
    else:
        engine_candidates = ["openpyxl", "xlrd"]

    last_error = None
    for engine in engine_candidates:
        try:
            return pd.read_excel(source_file, sheet_name=sheet_name, engine=engine)
        except Exception as exc:
            last_error = exc

    raise RuntimeError(str(last_error) if last_error else "No se pudo leer como Excel")


def try_get_sheet_names(source_file: Path) -> list[str]:
    """Get sheet names using explicit engines when possible."""
    suffix = source_file.suffix.lower()
    engine_candidates = []

    if suffix == ".xlsx":
        engine_candidates = ["openpyxl"]
    elif suffix == ".xls":
        engine_candidates = ["xlrd", "openpyxl"]
    else:
        engine_candidates = ["openpyxl", "xlrd"]

    last_error = None
    for engine in engine_candidates:
        try:
            xls = pd.ExcelFile(source_file, engine=engine)
            return list(xls.sheet_names)
        except Exception as exc:
            last_error = exc

    raise RuntimeError(str(last_error) if last_error else "No se pudo abrir como Excel")


def convert_html_tables_fallback(source_file: Path, destination_folder: Path) -> tuple[int, int]:
    """Fallback for .xls files that are HTML tables exported with .xls extension."""
    try:
        tables = pd.read_html(source_file, thousands=None, decimal=",")
    except Exception as exc:
        print(f"[ERROR] No se pudo abrir: {source_file} -> {exc}")
        return 0, 1

    if not tables:
        print(f"[WARN] No se encontraron tablas HTML en: {source_file}")
        return 0, 1

    generated = 0
    failed = 0

    for idx, df in enumerate(tables, start=1):
        try:
            if len(tables) == 1:
                csv_name = f"{source_file.stem}.csv"
            else:
                csv_name = f"{source_file.stem}__tabla_{idx}.csv"

            output_file = destination_folder / csv_name
            export_df_to_csv(df, output_file)
            print(f"[OK][HTML] {source_file} -> {output_file}")
            generated += 1
        except Exception as exc:
            print(f"[ERROR] Fallo al convertir tabla HTML #{idx} en {source_file}: {exc}")
            failed += 1

    return generated, failed


def convert_excel_file(source_file: Path, source_root: Path, output_root: Path) -> tuple[int, int]:
    """
    Convert one Excel file to CSV files.

    Returns:
        (generated_csv_count, failed_sheet_count)
    """
    relative_parent = source_file.parent.relative_to(source_root)
    destination_folder = output_root / relative_parent
    destination_folder.mkdir(parents=True, exist_ok=True)

    generated = 0
    failed = 0

    try:
        sheet_names = try_get_sheet_names(source_file)
    except Exception as exc:
        print(f"[WARN] No se pudo leer como Excel ({source_file}). Intentando como HTML: {exc}")
        return convert_html_tables_fallback(source_file, destination_folder)

    if not sheet_names:
        print(f"[WARN] El archivo no tiene hojas: {source_file}")
        return 0, 1

    single_sheet = len(sheet_names) == 1

    for sheet_name in sheet_names:
        try:
            df = try_read_excel(source_file, sheet_name=sheet_name)
            if single_sheet:
                csv_name = f"{source_file.stem}.csv"
            else:
                safe_sheet = make_safe_sheet_name(sheet_name)
                csv_name = f"{source_file.stem}__{safe_sheet}.csv"

            output_file = destination_folder / csv_name
            export_df_to_csv(df, output_file)
            print(f"[OK] {source_file} -> {output_file}")
            generated += 1
        except Exception as exc:
            print(f"[ERROR] Fallo al convertir hoja '{sheet_name}' en {source_file}: {exc}")
            failed += 1

    return generated, failed


def convert_tree(source_root: Path, output_root: Path, include_xlsx: bool) -> int:
    patterns = ["*.xls"]
    if include_xlsx:
        patterns.append("*.xlsx")

    excel_files: list[Path] = []
    for pattern in patterns:
        excel_files.extend(source_root.rglob(pattern))

    if not excel_files:
        print(f"No se encontraron archivos Excel en: {source_root}")
        return 1

    total_generated = 0
    total_failed = 0

    for excel_file in sorted(excel_files):
        generated, failed = convert_excel_file(excel_file, source_root, output_root)
        total_generated += generated
        total_failed += failed

    print("\nResumen:")
    print(f"  Archivos Excel detectados: {len(excel_files)}")
    print(f"  CSV generados: {total_generated}")
    print(f"  Errores: {total_failed}")

    return 0 if total_generated > 0 and total_failed == 0 else 2


def parse_args() -> argparse.Namespace:
    script_dir = Path(__file__).resolve().parent
    default_source = script_dir / "descargas"
    default_output = script_dir / "descargas_csv"

    parser = argparse.ArgumentParser(
        description=(
            "Convierte recursivamente archivos .xls de una carpeta a .csv UTF-8 "
            "manteniendo la misma estructura de carpetas."
        )
    )
    parser.add_argument(
        "--source",
        type=Path,
        default=default_source,
        help=f"Carpeta origen (por defecto: {default_source})",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=default_output,
        help=f"Carpeta destino (por defecto: {default_output})",
    )
    parser.add_argument(
        "--include-xlsx",
        action="store_true",
        help="Incluir tambien archivos .xlsx",
    )

    return parser.parse_args()


def main() -> int:
    args = parse_args()
    source_root = args.source.resolve()
    output_root = args.output.resolve()

    if not source_root.exists() or not source_root.is_dir():
        print(f"La carpeta origen no existe o no es valida: {source_root}")
        return 1

    output_root.mkdir(parents=True, exist_ok=True)

    convert_status = convert_tree(source_root, output_root, args.include_xlsx)
    workbooks_created, workbook_errors = build_workbooks_from_csv(output_root)

    print("\nConsolidacion en Excel:")
    print(f"  Excel creados: {workbooks_created}")
    print(f"  Errores: {workbook_errors}")

    if convert_status == 1:
        return 1
    if convert_status == 0 and workbook_errors == 0:
        return 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
